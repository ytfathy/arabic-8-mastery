async function main() {
  console.log('Pre-slicing all lessons...');
  for (const l of lessons) {
    const slicePath = `tmp_slices/${l.id}.pdf`;
    if (!fs.existsSync(slicePath)) {
      console.log(`Slicing ${l.id} (p${l.pages[0]}-${l.pages[1]})...`);
      await slicePages(l.pages[0], l.pages[1], slicePath);
    }
  }
  console.log('All slices created successfully!');

  for (const l of lessons) {
    const outTxt = `src/data/raw_${l.id}.txt`;
    if (fs.existsSync(outTxt) && fs.statSync(outTxt).size > 500) {
      console.log(`Already extracted: ${l.id}`);
      continue;
    }
    console.log(`Calling Gemini on ${l.id}...`);
    try {
      const pdfBytes = fs.readFileSync(`tmp_slices/${l.id}.pdf`);
      const text = await callGeminiOnPdf(pdfBytes, l.prompt);
      fs.writeFileSync(outTxt, text);
      console.log(`Saved ${outTxt} (${text.length} chars)`);
      await new Promise(r => setTimeout(r, 2000));
    } catch (e) {
      console.error(`Error on ${l.id}:`, e.message);
    }
  }
  console.log('Batch extraction complete!');
}

main().catch(console.error);
